"""Generates test frames as sent by an AMIS meter, encrypted independently of libamis
(Python 'cryptography'), and writes them as the C header test/vectors.h."""
import pathlib, struct
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

KEY = bytes.fromhex("00112233445566778899AABBCCDDEEFF")

def type_i(y, mo, d, h, mi, s, wd, wk, dst):
    yy = y - 2000
    return bytes([s | (0x40 if dst else 0), mi, h | (wd << 5), d | ((yy & 7) << 5), mo | ((yy >> 3) << 4), wk])

def payload(t, a_plus, a_minus, r_plus, r_minus, p_plus, p_minus, q_plus, q_minus, inkasso):
    u = lambda v: struct.pack("<I", v)
    p = b"\x2f\x2f" + b"\x06\x6d" + t
    p += b"\x04\x03" + u(a_plus) + b"\x04\x83\x3c" + u(a_minus)
    p += b"\x84\x10\xfb\x82\x73" + u(r_plus) + b"\x84\x10\xfb\x82\xf3\x3c" + u(r_minus)
    p += b"\x04\x2b" + u(p_plus) + b"\x04\xab\x3c" + u(p_minus)
    p += b"\x04\xfb\x14" + u(q_plus) + b"\x04\xfb\x94\x3c" + u(q_minus)
    p += b"\x04\x83\xff\x04" + struct.pack("<i", inkasso)
    p += b"\x2f" * (80 - len(p))
    assert len(p) == 80
    return p

def frame(plain, acc, key=KEY, c=0x53, ident=b"\x78\x56\x34\x12", man=b"\x2d\x4c", ver=1, med=0x0e):
    iv = man + ident + bytes([ver, med]) + bytes([acc]) * 8
    enc = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    data = enc.update(plain) + enc.finalize()
    body = bytes([c, 0xF0, 0x5B]) + ident + man + bytes([ver, med, acc, 0x00]) + struct.pack("<H", 0x0550) + data
    L = len(body)
    return bytes([0x68, L, L, 0x68]) + body + bytes([sum(body) & 0xFF, 0x16])

t = type_i(2026, 3, 28, 9, 20, 15, 6, 13, False)
F1 = frame(payload(t, 12345678, 2345678, 345678, 45678, 1234, 0, 210, 30, -42), acc=0x21)
F2 = frame(payload(type_i(2026, 3, 29, 23, 57, 55, 7, 13, True), 12345679, 2345690, 345678, 45680, 0, 3456, 0, 120, 7),
           acc=0x22, c=0x73)
NKE = bytes([0x10, 0x40, 0xF0, 0x30, 0x16])

def c_arr(name, b):
    body = ",".join("0x%02x" % x for x in b)
    return "static const uint8_t %s[%d] = {%s};\n" % (name, len(b), body)

out = "// Generated by test/gen_vectors.py - do not edit by hand\n#pragma once\n#include <stdint.h>\n"
out += 'static const char *kTestKeyHex = "%s";\n' % KEY.hex().upper()
out += c_arr("kFrame1", F1) + c_arr("kFrame2", F2) + c_arr("kSndNke", NKE)
(pathlib.Path(__file__).parent / "vectors.h").write_text(out)
print("ok", len(F1), F1[:20].hex())
